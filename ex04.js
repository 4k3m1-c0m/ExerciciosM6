function tiposDeErros() {
    console.log(
        "ReferenceError: acontece quando o código tenta acessar uma variável ou referência que não existe."
    );

    console.log(
        "TypeError: acontece quando uma operação é realizada em um valor de tipo inadequado."
    );

    console.log(
        "SyntaxError: acontece quando o código possui uma sintaxe inválida e não pode ser interpretado corretamente."
    );
}

tiposDeErros();